<?php

declare(strict_types=1);

$dumpPath = $argv[1] ?? '/DataBaseDump.sql';
if (!is_file($dumpPath)) {
    $fallbackPath = dirname(__DIR__) . '/DataBaseDump.sql';
    $dumpPath = is_file($fallbackPath) ? $fallbackPath : $dumpPath;
}

if (!is_file($dumpPath)) {
    fwrite(STDERR, "SQL dump not found at {$dumpPath}\n");
    exit(1);
}

$host = getenv('POSTGRES_HOST') ?: 'postgres';
$port = getenv('POSTGRES_PORT') ?: '5432';
$database = getenv('POSTGRES_DB') ?: 'bookswap_vectors';
$username = getenv('POSTGRES_USER') ?: 'developer';
$password = getenv('POSTGRES_PASSWORD') ?: 'secret123';

$dsn = "pgsql:host={$host};port={$port};dbname={$database}";
$pdo = new PDO($dsn, $username, $password, [
    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
]);

$dumpSql = file_get_contents($dumpPath);
if ($dumpSql === false) {
    fwrite(STDERR, "Failed to read SQL dump at {$dumpPath}\n");
    exit(1);
}

$pdo->beginTransaction();

try {
    createSchema($pdo);

    $insertBlocks = parseInsertBlocks($dumpSql);
    $importOrder = ['users', 'books', 'book_swap_requests', 'direct_messages'];

    foreach ($importOrder as $table) {
        if (!isset($insertBlocks[$table])) {
            echo "No rows found for {$table}\n";
            continue;
        }

        $imported = 0;
        foreach ($insertBlocks[$table] as $block) {
            $imported += insertRows($pdo, $table, $block['columns'], $block['rows']);
        }

        echo "Imported {$imported} rows into {$table}\n";
    }

    addIndexesAndConstraints($pdo);
    resetSequences($pdo);

    $pdo->commit();
    echo "Migration completed successfully.\n";
} catch (Throwable $e) {
    $pdo->rollBack();
    fwrite(STDERR, "Migration failed: {$e->getMessage()}\n");
    exit(1);
}

